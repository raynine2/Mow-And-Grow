#!/usr/bin/env python3
"""The grass clumps in studded blocks (9 Nov, owner: "make the grass thing also more stud like like u did").

Runs the voxel clump generator (tools/blender/voxel, without Blender) and writes src/shared/StudClumpShapes.luau:
for every Clump_<area>_<n>, its voxels gathered 3 x 3 x 3 into chunky cells (each cell its most common colour,
cells with fewer than 4 voxels dropped), stacked cells of one colour merged into one block. About 26-37 blocks a
clump. server/Field builds them over the mesh (Config.STUD_CLUMPS) and hides the mesh.

    python3 tools/stud_clumps.py
"""
import os
import sys
import types
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
for m in ("bpy", "bmesh", "mathutils"):
    sys.modules[m] = types.ModuleType(m)
sys.path.insert(0, os.path.join(HERE, "blender", "voxel"))
import models  # noqa: E402

F, MIN = 3, 4

out = [
    "-- GENERATED by tools/stud_clumps.py (do not edit by hand): the voxel grass clumps as chunky studded blocks.",
    "-- Per clump: lo / hi = the voxel bounds (voxels), pal = colours, boxes = { x0, y0, z0, x1, y1, z1, colour } in",
    "-- voxels (a voxel's cube spans v..v+1). server/Field maps the bounds onto the clump mesh's own box.",
    "local C = Color3.fromRGB",
    "return {",
]
for name, (fn, kw) in models.catalogue().items():
    if not name.startswith("Clump_"):
        continue
    vox, pal, vs = fn(**kw)
    cells = {}
    for (x, y, z), c in vox.items():
        cells.setdefault((x // F, y // F, z // F), []).append(c)
    cells = {k: Counter(v).most_common(1)[0][0] for k, v in cells.items() if len(v) >= MIN}
    used, boxes = set(), []
    for k in sorted(cells, key=lambda k: (k[1], k[0], k[2])):
        if k in used:
            continue
        x, y, z = k
        c = cells[k]
        h = 1
        while (x, y + h, z) in cells and cells[(x, y + h, z)] == c and (x, y + h, z) not in used:
            h += 1
        for j in range(h):
            used.add((x, y + j, z))
        boxes.append((x * F, y * F, z * F, x * F + F, (y + h) * F, z * F + F, c + 1))
    xs = [k[0] for k in vox]
    ys = [k[1] for k in vox]
    zs = [k[2] for k in vox]
    pals = ", ".join(f"C({r}, {g}, {b})" for (r, g, b) in pal)
    bx = ", ".join("{ " + ", ".join(str(v) for v in b) + " }" for b in boxes)
    out.append(f"\t{name} = {{ lo = {{ {min(xs)}, {min(ys)}, {min(zs)} }}, hi = {{ {max(xs) + 1}, {max(ys) + 1}, {max(zs) + 1} }}, pal = {{ {pals} }}, boxes = {{ {bx} }} }},")
    print(f"{name:18s} {len(boxes)} blocks")
out.append("}")
path = os.path.join(HERE, "..", "src", "shared", "StudClumpShapes.luau")
with open(path, "w") as f:
    f.write("\n".join(out) + "\n")
print("wrote", os.path.normpath(path))
